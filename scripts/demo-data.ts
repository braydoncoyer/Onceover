const files: Record<string, ChangedFile> = {};
const keyOf = (file: ChangedFile) => {
  const json = JSON.stringify(file);
  const key = createHash('sha1').update(json).digest('hex').slice(0, 12);
  files[key] = file;
  return key;
};

async function snapshot(base: string): Promise<DemoSnapshot> {
  const review = await loadReview({ cwd: repo, base });
  const meta: MetaResponse = {
    repo: review.repo.name,
    branch: review.repo.branch,
    shortHead: review.repo.shortHead,
    head: review.repo.head,
    base: { ...review.base, source: 'origin-head' },
    defaultBase: detected.ref,
    mergeBase: review.mergeBase,
    worktree: SHOWN_WORKTREE,
    isLinkedWorktree: false,
  };
  return { meta, head: review.repo.head, mergeBase: review.mergeBase, files: review.files.map(keyOf) };
}

