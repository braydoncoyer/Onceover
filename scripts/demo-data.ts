const linesOf = (text: string | null) => (text ?? '').replace(/\n$/, '').split('\n');
const at = (minute: number) => new Date(Date.UTC(2026, 9, 24, 15, minute)).toISOString();

/** A line comment on the lines holding `first`, `count` lines long, with the context the page saves. */
function lineComment(id: string, path: string, side: 'new' | 'old', first: string, count: number, body: string, minute: number): ReviewComment {
  const file = fileAt(path);
  const lines = linesOf(side === 'new' ? file.newContents : file.oldContents);
  const index = lines.findIndex((line) => line.includes(first));
  if (index < 0) throw new Error(`No "${first}" in ${path}.`);
  return {
    id,
    path,
    side,
    start: index + 1,
    end: index + count,
    text: lines.slice(index, index + count),
    before: lines.slice(Math.max(0, index - 2), index),
    after: lines.slice(index + count, index + count + 2),
    body,
    outdated: false,
    createdAt: at(minute),
    updatedAt: at(minute),
  };
}

