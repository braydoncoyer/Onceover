/** Mock rides for tests: thousands of lines, so the card waits behind Load diff. */
function rideFixtures(count: number, withByline: boolean) {
  const rows = Array.from({ length: count }, (_, i) => {
    const status = STATUSES[i % STATUSES.length];
    const id = `ride_${String(i + 1).padStart(4, '0')}`;
    const fare = 900 + ((i * 137) % 3400);
    const route = `from: '${STOPS[i % STOPS.length]}', to: '${STOPS[(i * 3 + 1) % STOPS.length]}'`;
    return withByline
      ? `  { id: '${id}', status: '${status}', ${route}, fare: ${fare}, byline: ${status === 'driver-assigned' ? "'Driver en route'" : status === 'in-progress' ? "'Trip in progress'" : 'null'} },`
      : `  { id: '${id}', status: '${status}', ${route}, fareCents: ${fare}, dimmed: ${status === 'cancelled-by-driver'} },`;
  });
  return `// Generated by scripts/mock-rides.ts. Edit the generator, not this file.\nimport type { MockRide } from './types';\n\nexport const rides: MockRide[] = [\n${rows.join('\n')}\n];\n`;
}

