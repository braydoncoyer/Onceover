const git = (cwd: string, ...args: string[]) => {
  // Fixed, increasing dates keep the SHAs the same from one build to the next.
  clock += 3_600_000;
  const date = new Date(clock).toISOString();
  return execFileSync('git', args, { cwd, env: { ...gitEnv, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date }, stdio: 'pipe' })
    .toString()
    .trim();
};
const write = (dir: string, files: Record<string, string | Buffer>) => {
  for (const [path, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), contents);
  }
};
const edit = (dir: string, path: string, change: (text: string) => string) => {
  const file = join(dir, path);
  const before = readFileSync(file, 'utf8');
  const after = change(before);
  if (after === before) throw new Error(`Demo edit to ${path} changed nothing.`);
  writeFileSync(file, after);
};

